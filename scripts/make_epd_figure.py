"""Writes figures/epd_rules.tex: TikZ sketch of the interface-order rules EPD0, StrictEPD0, EPD1, EPD2.

A lattice patch with nearest-neighbour edges stands in for the neighbour graph. The particle in the
centre has been lowered to order 1, all others have order K. Every edge (a, b) is drawn as two halves;
the half next to a shows the order k_{a->b} with which a's reconstruction enters the interface:
red = order 1 (piecewise constant), grey = order K.
"""
import os

NX, NY = 7, 5
S = 0.56                      # lattice spacing in cm
P = (3, 2)                    # lowered particle


def nbrs(a):
    x, y = a
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        b = (x + dx, y + dy)
        if 0 <= b[0] < NX and 0 <= b[1] < NY:
            yield b


def orders(rule):
    k = {(x, y): 4 for x in range(NX) for y in range(NY)}
    k[P] = 1
    if rule == "StrictEPD0":
        for b in nbrs(P):
            k[b] = 1
    return k


def side_order(rule, k, a, b):
    if rule in ("EPD0", "StrictEPD0"):
        return k[a]
    if rule == "EPD1":
        return min(k[a], k[b])
    if rule == "EPD2":
        closed = {a, b} | set(nbrs(a)) | set(nbrs(b))
        return min(k[c] for c in closed)
    raise ValueError(rule)


def panel(rule, x0):
    k = orders(rule)
    lines = []
    edges = set()
    for x in range(NX):
        for y in range(NY):
            for b in nbrs((x, y)):
                edges.add(tuple(sorted(((x, y), b))))
    for a, b in sorted(edges):
        for u, v in ((a, b), (b, a)):
            o = side_order(rule, k, u, v)
            col = "lowc" if o == 1 else "highc"
            w = "very thick" if o == 1 else "thick"
            ux, uy = x0 + u[0] * S, u[1] * S
            mx, my = x0 + (u[0] + v[0]) * S / 2, (u[1] + v[1]) * S / 2
            lines.append(f"\\draw[{col},{w}] ({ux:.3f},{uy:.3f}) -- ({mx:.3f},{my:.3f});")
    for x in range(NX):
        for y in range(NY):
            cx, cy = x0 + x * S, y * S
            if (x, y) == P:
                lines.append(f"\\fill[lowc] ({cx:.3f},{cy:.3f}) circle (2.4pt);")
            elif k[(x, y)] == 1:
                lines.append(f"\\filldraw[fill=white,draw=lowc,line width=1.1pt] ({cx:.3f},{cy:.3f}) circle (2.1pt);")
            else:
                lines.append(f"\\fill[black] ({cx:.3f},{cy:.3f}) circle (1.5pt);")
    lines.append(f"\\node[anchor=south] at ({x0 + (NX - 1) * S / 2:.3f},{(NY - 1) * S + 0.12:.3f}) {{\\small {rule}}};")
    return lines


def main():
    out = []
    out.append("% generated by scripts/make_epd_figure.py")
    out.append("\\begin{tikzpicture}")
    gap = 0.70
    width = (NX - 1) * S
    for n, rule in enumerate(("EPD0", "StrictEPD0", "EPD1", "EPD2")):
        out += panel(rule, n * (width + gap))
    out.append("\\end{tikzpicture}")
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "..", "figures", "epd_rules.tex")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("written", os.path.normpath(path))


if __name__ == "__main__":
    main()
