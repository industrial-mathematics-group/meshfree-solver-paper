"""Helpers for the high-order stability study (companion to linop.py).

  * volumes(P, h)             : particle volumes (1-D: dual volumes half the neighbour distances, else 1/N)
  * sym_abscissa(L, V)        : numerical abscissa of L in the V-weighted inner product, max eig of (VL+L^T V)/2 w.r.t. V
  * kreiss(L, V, ts)          : sup_t ||exp(tL)||_V over a set of times (eigen-decomposition if diagonalizable, else expm)
  * bloch_symbol(P0, h0, ...) : m x m Bloch symbols of a periodic cloud (supercell P0 of period 1 in every direction)
  * deformed_cloud(n, D, A)   : smoothly deformed lattice x = phi(s), phi(s) = s + A sin(2 pi s)/(2 pi) per coordinate
All operators are assembled by linop.build_operator (no MOOD, no limiter, linear advection, s_d = |a_d|).
"""
import itertools
import sys

import numpy as np
import scipy.linalg as sl

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from linop import build_operator, first_order_operator, neighbours  # noqa: E402,F401


def volumes(P, h, kind="dual"):
    N, D = P.shape
    if D == 1 and kind == "dual":
        x = np.sort(P[:, 0])
        order = np.argsort(P[:, 0])
        gaps = np.diff(np.concatenate([x, [x[0] + 1.0]]))          # gap i: between sorted i and i+1
        V = np.empty(N)
        V[order] = 0.5 * (gaps + np.roll(gaps, 1))
        return V
    return np.full(N, 1.0 / N)


def sym_abscissa(L, V):
    """max eigenvalue of the V-symmetric part: max_U <U, L U>_V / <U, U>_V."""
    Vm = np.diag(V)
    A = 0.5 * (Vm @ L + L.T @ Vm)
    return sl.eigh(A, Vm, eigvals_only=True)[-1]


def kreiss(L, V, ts):
    """sup over ts of the V-norm of exp(tL)."""
    s = np.sqrt(V)
    Ls = (s[:, None] * L) / s[None, :]
    best = 0.0
    try:
        ev, X = np.linalg.eig(Ls)
        Xi = np.linalg.inv(X)
        cond = np.linalg.cond(X)
        for t in ts:
            E = (X * np.exp(t * ev)[None, :]) @ Xi
            best = max(best, np.linalg.norm(E.real, 2))
        if cond > 1e8:   # fall back to expm for ill-conditioned eigenbases
            raise np.linalg.LinAlgError
    except np.linalg.LinAlgError:
        best = 0.0
        for t in ts:
            best = max(best, np.linalg.norm(sl.expm(t * Ls), 2))
    return best


def default_times(h, tmax=20.0, n=40):
    """log-spaced times from h/100 to tmax (covers the transient of rough modes and the long-time behaviour)."""
    return np.logspace(np.log10(h / 100.0), np.log10(tmax), n)


def supercell_cloud(P0, copies=3):
    """Tile the supercell P0 (period 1 per direction) copies^D times and scale to the unit torus."""
    N0, D = P0.shape
    shifts = np.array(list(itertools.product(range(copies), repeat=D)), float)
    P = np.concatenate([(P0 + s) / copies for s in shifts])          # block k = shift index
    return np.mod(P, 1.0), shifts


def bloch_symbols(P0, kappa, K, a, orient, thetas, copies=3, q=None):
    """Bloch symbols Lhat(theta) (N0 x N0, complex) of the periodic cloud generated by the supercell P0.

    Row p of the middle block, column (q, shift k): contributes L[p_mid, (q,k)] exp(i theta . (k - mid)).
    Entries are in the units of the tiled unit-torus cloud with spacing h = 1/(copies * m); returns (symbols, h).
    """
    N0, D = P0.shape
    m = round(N0 ** (1.0 / D))
    h = 1.0 / (copies * m)
    P, shifts = supercell_cloud(P0, copies)
    mid = (copies - 1) // 2
    kmid = int(np.where((shifts == mid).all(1))[0][0])
    L = build_operator(P, h, kappa, K, a, orient, q=q) if K >= 2 else first_order_operator(P, h, kappa, a)
    rows = L[kmid * N0:(kmid + 1) * N0, :]                    # N0 x (copies^D N0)
    syms = []
    for th in thetas:
        th = np.atleast_1d(th)
        phase = np.exp(1j * (shifts - mid) @ th)                # per block
        S = np.zeros((N0, N0), complex)
        for b in range(len(shifts)):
            S += rows[:, b * N0:(b + 1) * N0] * phase[b]
        syms.append(S)
    return syms, h


def deformed_cloud(n, D, A, seed=None):
    """x = phi(s) on the lattice s = (i + 1/2)/n, phi(s) = s + A sin(2 pi s)/(2 pi) per coordinate (A < 1)."""
    h = 1.0 / n
    g = (np.arange(n) + 0.5) * h
    S = np.stack(np.meshgrid(*([g] * D), indexing="ij"), axis=-1).reshape(-1, D)
    P = S + A * np.sin(2 * np.pi * S) / (2 * np.pi)
    return np.mod(P, 1.0), h, S


def jacobian_volumes(S, A, h):
    """exact volumes det(phi'(s)) h^D of the deformed lattice."""
    return np.prod(1.0 + A * np.cos(2 * np.pi * S), axis=1) * h ** S.shape[1]
